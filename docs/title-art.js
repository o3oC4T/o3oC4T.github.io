export function titleArt(title) {
  const letters = [...title.toUpperCase()].map(letter => {
    if (!alphabet[letter]) throw new Error(`Unsupported title character: ${letter}`);
    return alphabet[letter];
  });
  const width = letters.reduce((total, letter) => total + letter[0].length * 2 + 2, 0);
  const pixels = Array.from({ length: 16 }, () => Array(width).fill(' '));
  const face = [];
  let offset = 0;
  for (const letter of letters) {
    letter.forEach((row, y) => [...row].forEach((value, x) => {
      if (value !== '1') return;
      for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) face.push([offset + x * 2 + dx, y * 2 + dy]);
    }));
    offset += letter[0].length * 2 + 2;
  }
  for (const [x, y] of face) pixels[y + 2][x + 2] = '░';
  for (const [x, y] of face) pixels[y + 1][x + 1] = '▒';
  for (const [x, y] of face) pixels[y][x] = x % 6 === 0 ? '▓' : '█';
  return pixels.map(row => row.join(''));
}
